//! Errors. Contract: `spec/object.md` "Errors".

use std::fmt;

use crate::model::{SectionId, SymbolId};
use crate::reloc::RelocKind;

/// A count or size that does not fit the object-file format.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Limit {
    /// Symbol names exceed the 4 GiB a 32-bit `st_name` can address.
    StringBytes,
    /// Section names exceed the 4 GiB a 32-bit `sh_name` can address.
    SectionNameBytes,
    /// More sections than a 32-bit section index can number.
    Sections,
    /// More symbols than a 32-bit symbol index can number.
    Symbols,
    /// More relocations than a 32-bit index can number.
    Relocations,
    /// More groups than a 32-bit index can number.
    Groups,
}

/// Why a symbol cannot be written.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SymbolProblem {
    /// Its `name` was not issued by this object's `add_string`.
    UnknownName,
    /// Its `place` names a section this object does not have.
    UnknownSection,
    /// It is undefined and local; only the null symbol may be.
    UndefinedLocal,
    /// A section symbol must be local and placed in a section.
    SectionSymbolShape,
    /// A file symbol must be local and absolute.
    FileSymbolShape,
    /// `other` has bits in the visibility field (the low two bits).
    OtherOverlapsVisibility,
}

/// Why an object cannot be built or written.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Error {
    /// A name contains a NUL byte.
    NulInName,
    /// An alignment is not a power of two.
    BadAlignment {
        /// The alignment given.
        align: u64,
    },
    /// A mergeable section's entry size is zero, or its size is not a
    /// multiple of its entry size.
    BadEntrySize {
        /// The section, when the problem was found at write time.
        section: Option<SectionId>,
    },
    /// `SectionKind::Elf` named a section type the writer generates itself.
    ReservedSectionType {
        /// The `sh_type` given.
        sh_type: u32,
    },
    /// `SectionKind::Elf` set a flag the writer sets itself.
    ReservedSectionFlags {
        /// The offending bits of `sh_flags`.
        sh_flags: u64,
    },
    /// A count or size does not fit the format.
    TooLarge(Limit),
    /// A relocation kind of another architecture was added.
    RelocationArchMismatch {
        /// The section the relocation was added to.
        section: SectionId,
        /// The kind given.
        kind: RelocKind,
    },
    /// Bytes were stored in a section that occupies no file space.
    DataInNobits {
        /// The section.
        section: SectionId,
    },
    /// A section that occupies no file space has relocations.
    RelocationInNobits {
        /// The section.
        section: SectionId,
    },
    /// A relocation's offset lies beyond the end of its section.
    RelocationOutOfBounds {
        /// The section.
        section: SectionId,
        /// The largest relocation offset in it.
        offset: u64,
    },
    /// A symbol cannot be written.
    BadSymbol {
        /// The symbol.
        symbol: SymbolId,
        /// Why.
        problem: SymbolProblem,
    },
    /// A section was added to a second group.
    SectionAlreadyInGroup {
        /// The section.
        section: SectionId,
    },
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match *self {
            Self::NulInName => f.write_str("name contains a NUL byte"),
            Self::BadAlignment { align } => write!(f, "alignment {align} is not a power of two"),
            Self::BadEntrySize { section: None } => f.write_str("entry size is zero"),
            Self::BadEntrySize { section: Some(s) } => {
                write!(f, "size of section #{} is not a multiple of its entry size", s.index())
            }
            Self::ReservedSectionType { sh_type } => {
                write!(f, "section type {sh_type:#x} is generated by the writer")
            }
            Self::ReservedSectionFlags { sh_flags } => {
                write!(f, "section flags {sh_flags:#x} are set by the writer")
            }
            Self::TooLarge(limit) => {
                let what = match limit {
                    Limit::StringBytes => "symbol names exceed 4 GiB",
                    Limit::SectionNameBytes => "section names exceed 4 GiB",
                    Limit::Sections => "too many sections",
                    Limit::Symbols => "too many symbols",
                    Limit::Relocations => "too many relocations",
                    Limit::Groups => "too many groups",
                };
                f.write_str(what)
            }
            Self::RelocationArchMismatch { section, kind } => write!(
                f,
                "relocation {kind:?} in section #{} is for another architecture",
                section.index()
            ),
            Self::DataInNobits { section } => {
                write!(f, "section #{} occupies no file space but has bytes", section.index())
            }
            Self::RelocationInNobits { section } => {
                write!(f, "section #{} occupies no file space but has relocations", section.index())
            }
            Self::RelocationOutOfBounds { section, offset } => write!(
                f,
                "relocation at offset {offset:#x} is beyond the end of section #{}",
                section.index()
            ),
            Self::BadSymbol { symbol, problem } => {
                let why = match problem {
                    SymbolProblem::UnknownName => "its name is not a string of this object",
                    SymbolProblem::UnknownSection => "its section does not exist",
                    SymbolProblem::UndefinedLocal => "it is undefined and local",
                    SymbolProblem::SectionSymbolShape => {
                        "a section symbol must be local and placed in a section"
                    }
                    SymbolProblem::FileSymbolShape => "a file symbol must be local and absolute",
                    SymbolProblem::OtherOverlapsVisibility => {
                        "`other` overlaps the visibility bits"
                    }
                };
                write!(f, "symbol #{}: {why}", symbol.index())
            }
            Self::SectionAlreadyInGroup { section } => {
                write!(f, "section #{} is already in a group", section.index())
            }
        }
    }
}

impl std::error::Error for Error {}

/// Why [`crate::elf::write`] failed.
#[derive(Debug)]
pub enum WriteError {
    /// The object is not writable; nothing was written.
    Invalid(Error),
    /// The sink failed; the output is incomplete.
    Io(std::io::Error),
}

impl fmt::Display for WriteError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Invalid(e) => write!(f, "invalid object: {e}"),
            Self::Io(e) => write!(f, "cannot write object: {e}"),
        }
    }
}

impl std::error::Error for WriteError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Invalid(e) => Some(e),
            Self::Io(e) => Some(e),
        }
    }
}

impl From<Error> for WriteError {
    fn from(e: Error) -> Self {
        Self::Invalid(e)
    }
}

impl From<std::io::Error> for WriteError {
    fn from(e: std::io::Error) -> Self {
        Self::Io(e)
    }
}
