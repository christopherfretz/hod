/// Rows for checks that are not single constructors: the materializer's
/// one-instruction results, and words patched by each fixup kind.
pub const OTHER: &[(&str, &[&str])] = &[
    ("mov_imm", &["mov", "movz", "movn", "orr"]),
    ("patch_jump26", &["b*"]),
    ("patch_branch19", &["b.*", "cb*"]),
    ("patch_test14", &["tb*"]),
    ("patch_adr21", &["adr*"]),
    ("patch_literal19", &["ldr*"]),
];

pub fn base_mnemonics(name: &str) -> Option<&'static [&'static str]> {
    CONSTRUCTORS.iter().chain(OTHER).find(|(row, _)| *row == name).map(|(_, mnemonics)| *mnemonics)
}
