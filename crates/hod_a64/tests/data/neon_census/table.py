#!/usr/bin/env python3
"""Folds the rows `census.py` printed for clang 19 and clang 22 into
`census.tsv` (WP-205): one line per `llvm.*` intrinsic (its name without
the type suffixes) and per plain vector instruction that reaches the back
end, with the header group and the feature of the header functions that
emit it, how many header functions emit it, and what `hod --strict`
answered for those functions.

Usage: python3 -B table.py <rows19.tsv> <rows22.tsv> > census.tsv

Columns: `name  kind  group  feature  functions  built  refused  answer`.
`functions` counts the distinct header functions (of either clang) that
emit the name; `built`/`refused` count those hod builds and refuses;
`answer` is `built`, or the refusals named for it (most frequent first).
A refusal is charged to every name of the function (a wrapper emits one
or two), so a name built by itself may show the refusal of its neighbour.
The trailer lists the header functions that do not compile with either
clang (the AArch32-only ACLE functions and the system-register and MTE
macros whose operands the generator cannot make).
"""

import sys
from collections import Counter, defaultdict


def rows(path):
    for line in open(path, encoding="utf-8"):
        f = line.rstrip("\n").split("\t")
        if len(f) == 7:
            yield f


def main():
    seen = defaultdict(lambda: {"fns": set(), "groups": Counter(), "feats": Counter(),
                                "built": set(), "refused": Counter(), "kind": "",
                                "refused_fns": set()})
    failed, total = set(), set()
    compiled = set()
    for path in sys.argv[1:3]:
        for header, fn, feat, group, names, insts, answer in rows(path):
            total.add(fn)
            if names == "(does not compile)":
                failed.add(fn)
                continue
            compiled.add(fn)
            items = [(n, "intrinsic") for n in names.split()]
            items += [(i, "instruction") for i in insts.split()]
            for n, kind in items:
                s = seen[n]
                s["kind"] = kind
                s["fns"].add(fn)
                s["groups"][group] += 1
                s["feats"][feat] += 1
                if answer == "built":
                    s["built"].add(fn)
                else:
                    s["refused"][answer] += 1
                    s["refused_fns"].add(fn)
    print("# Generated by table.py from census.py's rows for clang 19 and 22: do not edit.")
    print("# name\tkind\tgroup\tfeature\tfunctions\tbuilt\trefused\tanswer")
    for n in sorted(seen, key=lambda n: (seen[n]["kind"], n)):
        s = seen[n]
        group = s["groups"].most_common(1)[0][0]
        feat = s["feats"].most_common(1)[0][0]
        refused = s["refused_fns"]
        answer = "built" if not refused else ",".join(r for r, _ in s["refused"].most_common())
        print(f"{n}\t{s['kind']}\t{group}\t{feat}\t{len(s['fns'])}\t"
              f"{len(s['built'] - refused)}\t{len(refused)}\t{answer}")
    never = sorted(failed - compiled)
    print(f"# {len(total)} header functions, {len(total) - len(never)} compiled; "
          f"not compiled by either clang ({len(never)}): {' '.join(never)}")


if __name__ == "__main__":
    main()
