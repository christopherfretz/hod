#!/usr/bin/env python3
"""Generates `cases.txt` for `crates/hod_a64/tests/neon.rs` (WP-083).

One call per signature of each AArch64 intrinsic on `hod_ir`'s list but
the bfloat ones and `crc32` (and per immediate for those that take one),
as `<ret> @<name>(<args>)` where `<type> %` is a register operand;
`neon.rs` makes each a function of six `i64` arguments that loads those
operands from bytes derived from the arguments and hashes the result.

Usage: cases.py <signatures>... > cases.txt, each file one declaration
per line as `llvm-dis` prints it (the declarations clang 22 and 19 emit
for `<arm_neon.h>` and `<arm_acle.h>`, and those of the corpus).
"""

import re
import sys

DECL = re.compile(r"^(.*?) @(llvm\.aarch64\.[\w.]+)\((.*)\)$")

# The intrinsics the test exercises: (prefix, kind of immediate).
LAST_SHIFT = ("neon.vcvtfp2fxs", "neon.vcvtfp2fxu", "neon.vcvtfxs2fp", "neon.vcvtfxu2fp",
              "neon.vsli", "neon.vsri", "neon.rshrn", "neon.sqshrn", "neon.sqrshrn",
              "neon.sqshrun", "neon.sqrshrun", "neon.uqshrn", "neon.uqrshrn", "crypto.xar")
SKIP = ("neon.bf", "crc32")
# The intrinsic list of `hod_ir`, whose AArch64 members this test covers.
LIST = __file__.rsplit("/crates/", 1)[0] + "/crates/hod_ir/src/intrinsic.rs"
BASES = re.findall(r'"llvm\.aarch64\.([\w.]+)"', open(LIST, encoding="utf-8").read())
SYSTEM = {"dmb": [1, 9, 11, 15], "dsb": [3, 14, 15], "isb": [15], "hint": [0, 1, 7, 34]}


def split_params(text):
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch in "<{":
            depth += 1
        elif ch in ">}":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return [re.sub(r"\s+(immarg|noundef|nocapture|readonly|writeonly|captures\(none\))", "", p)
            for p in out]


def vec(ty):
    m = re.match(r"<(\d+) x (\w+)>$", ty)
    return (int(m.group(1)), m.group(2)) if m else None


BITS = {"i8": 8, "i16": 16, "i32": 32, "i64": 64, "half": 16, "float": 32, "double": 64,
        "bfloat": 16}


def elem_bits(ty):
    v = vec(ty)
    return BITS[v[1]] if v else BITS.get(ty, 64)


def size(ty):
    v = vec(ty)
    if v:
        return v[0] * BITS[v[1]] // 8
    if ty.startswith("{"):
        return sum(size(t) for t in split_params(ty[1:-1]))
    return BITS[ty] // 8


def immediates(name, ret, params):
    """[(index, [values])] of the immediate operands."""
    base = name[len("llvm.aarch64."):]
    if base.startswith(LAST_SHIFT):
        i = len(params) - 1
        if base.startswith("crypto.xar"):
            return [(i, [0, 1, 63])]
        if base.startswith(("neon.vcvtfp2fx", "neon.vcvtfx")):
            b = elem_bits(params[0])
            return [(i, [1, b // 2, b])]
        if base.startswith("neon.vsli"):
            b = elem_bits(ret)
            return [(i, [0, 1, b - 1])]
        if base.startswith("neon.vsri"):
            b = elem_bits(ret)
            return [(i, [1, b // 2, b])]
        b = elem_bits(ret)  # the narrowing shifts
        return [(i, [1, b // 2 + 1, b])]
    if re.match(r"neon\.sq(r)?dmulh\.lane", base):
        n = vec(params[1])[0]
        return [(2, [0, n - 1])]
    if re.match(r"neon\.(ld|st)\dlane", base):
        k = int(base[7])
        n = vec(params[0])[0]
        return [(k, [0, n - 1])]
    return []


def main():
    decls = {}
    for path in sys.argv[1:]:
        for line in open(path, encoding="utf-8"):
            m = DECL.match(line.strip())
            if not m:
                continue
            ret, name, params = m.group(1), m.group(2), split_params(m.group(3))
            base = name[len("llvm.aarch64."):]
            stem = next((b for b in sorted(BASES, key=len, reverse=True)
                         if re.fullmatch(re.escape(b) + r"(\.[a-z0-9]+)*", base)
                         and not re.match(r"\.(lane|laneq)", base[len(b):])), None)
            if stem is None or stem.startswith(SKIP) or "bfloat" in line:
                continue
            decls.setdefault(name, (ret, params))
    out = ["# Generated by cases.py: do not edit. One call per line; `<type> %` is an",
           "# operand loaded from the input buffer, anything else is passed as written."]
    for name in sorted(decls):
        ret, params = decls[name]
        base = name[len("llvm.aarch64."):]
        if base in SYSTEM:
            out += [f"void @{name}(i32 {v})" for v in SYSTEM[base]]
            continue
        choices = [[]]
        for i, vals in immediates(name, ret, params):
            choices = [c + [(i, v)] for c in choices for v in vals]
        for choice in choices:
            out.append(call(len(out), name, ret, params, dict(choice)))
    print("\n".join(out))
    print(f"{len(out) - 2} calls, {len(decls)} declarations", file=sys.stderr)


def call(k, name, ret, params, fixed):
    args = []
    store = name.startswith("llvm.aarch64.neon.st")
    for i, ty in enumerate(params):
        if i in fixed:
            args.append(f"{ty} {fixed[i]}")
        elif ty == "ptr":
            args.append("ptr %out" if store else "ptr %in")
        elif name.startswith("llvm.aarch64.neon.sqshlu") and i == 1:
            b = elem_bits(ty)
            v = [0, 1, b // 2, b - 1][(k + sum(map(ord, ty))) % 4]
            n = vec(ty)
            args.append(f"{ty} splat ({n[1]} {v})" if n else f"{ty} {v}")
        else:
            args.append(f"{ty} %")
    return f"{ret} @{name}({', '.join(args)})"


if __name__ == "__main__":
    main()
